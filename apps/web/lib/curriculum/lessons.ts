export interface LessonExercise {
  /** Markdown; its `###` sections become the steps of the explanation (see steps.ts). */
  explanation: string;
  starterCode: string;
  checks: LessonCheck[];
  /** Optional questions shown between steps. */
  quizzes?: LessonQuiz[];
}

interface LessonBase {
  /** Lesson id, also the ERC-1155 token id of its certificate. */
  id: number;
  slug: string;
  title: string;
  difficulty: string;
  xp: number;
  /** Id of the module (curriculum/modules.json) the lesson belongs to. */
  module: string;
  /** One line on what the student builds, shown on the lesson card. */
  preview: string;
  /** Estimated time to complete the lesson, in minutes. */
  minutes: number;
}

/** Available lessons have an exercise; unavailable ones are listed as coming soon. */
export type Lesson = LessonBase &
  ({ available: true; exercise: LessonExercise } | { available: false; exercise?: undefined });

interface LessonContent {
  slug: string;
  difficulty: string;
  preview: string;
  minutes: number;
  exercise?: LessonExercise;
}

/**
 * Snippets for a lesson 8 lookup that reverts with UnknownTask past the end of the list: `ok_or`,
 * `ok_or_else`, or a `match` whose arms, up to the `Err(`, are one of `arms`. Each snippet starts at
 * the lookup, so a revert written for another lookup does not count.
 */
function revertingLookups(lookups: string[], arms: string[]): string[] {
  const unknownTask = 'TodoError::UnknownTask(UnknownTask {';
  return lookups.flatMap((lookup) => [
    `${lookup}.ok_or(${unknownTask}`,
    `${lookup}.ok_or_else(|| ${unknownTask}`,
    ...arms.map((arm) => `match ${lookup} { ${arm} Err(${unknownTask}`),
  ]);
}

