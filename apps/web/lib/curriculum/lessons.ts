export interface LessonExercise {
  /** Markdown; its `###` sections become the steps of the explanation (see steps.ts). */
  explanation: string;
  starterCode: string;
  checks: LessonCheck[];
  /** Optional questions shown between steps. */
  quizzes?: LessonQuiz[];
}

interface LessonBase {
  /** Lesson id, also the ERC-1155 token id of its certificate. */
  id: number;
  slug: string;
  title: string;
  difficulty: string;
  xp: number;
  /** Id of the module (curriculum/modules.json) the lesson belongs to. */
  module: string;
  /** One line on what the student builds, shown on the lesson card. */
  preview: string;
  /** Estimated time to complete the lesson, in minutes. */
  minutes: number;
}

/** Available lessons have an exercise; unavailable ones are listed as coming soon. */
export type Lesson = LessonBase &
  ({ available: true; exercise: LessonExercise } | { available: false; exercise?: undefined });

interface LessonContent {
  slug: string;
  difficulty: string;
  preview: string;
  minutes: number;
  exercise?: LessonExercise;
}

/**
 * Snippets for a lesson 8 lookup that reverts with UnknownTask past the end of the list: `ok_or`,
 * `ok_or_else`, or a `match` whose arms, up to the `Err(`, are one of `arms`. Each snippet starts at
 * the lookup, so a revert written for another lookup does not count.
 */
function revertingLookups(lookups: string[], arms: string[]): string[] {
  const unknownTask = 'TodoError::UnknownTask(UnknownTask {';
  return lookups.flatMap((lookup) => [
    `${lookup}.ok_or(${unknownTask}`,
    `${lookup}.ok_or_else(|| ${unknownTask}`,
    ...arms.map((arm) => `match ${lookup} { ${arm} Err(${unknownTask}`),
  ]);
}

/**
 * Snippets for lesson 13's guard that leaves an unlimited allowance untouched: the allowance compared
 * with `U256::MAX`, either way round, right before the write of the lowered allowance (or before the
 * local that holds it).
 */
function unlimitedGuards(): string[] {
  const guards = ['if $a != U256::MAX {', 'if $a < U256::MAX {', 'if U256::MAX != $a {', 'if U256::MAX > $a {'];
  return guards.flatMap((guard) => [`${guard} self.allowances.setter(from)`, `${guard} let $y = $a - value; self.allowances.setter(from)`]);
}

/**
 * Snippets for returning a custom error: built in place (`Err(Enum::Variant(Variant { fields }))`),
 * or kept in a local first, either the error or the enum variant. Each entry of `fieldLists` is one
 * accepted way to write the fields; rustfmt may add a trailing comma.
 */
function errorReturns(enumName: string, variant: string, fieldLists: string[]): string[] {
  return fieldLists.flatMap((fields) =>
    [`${variant} { ${fields} }`, `${variant} { ${fields}, }`].flatMap((error) => [
      `return Err(${enumName}::${variant}(${error}))`,
      `let $x = ${error}; return Err(${enumName}::${variant}($x))`,
      `let $x = ${enumName}::${variant}(${error}); return Err($x)`,
    ]),
  );
}

/** Snippets for an `if` with one of `conditions` that returns one of `errors` first thing. */
function guardedReturns(conditions: string[], errors: string[]): string[] {
  return conditions.flatMap((condition) => errors.map((error) => `${condition} ${error}`));
}

/**
 * Snippets for lesson 14's balance updates: `account`'s balance with one token added or taken
 * (`U256::from(1)` or `U256::ONE`), written with `insert` or `setter`, directly or from a local.
 * The balance is read into a local first, or inline in `insert` only: inline in `setter(..).set(..)`,
 * the read would borrow the mapping while the setter holds it, which does not compile.
 */
function balanceUpdates(account: string, op: '+' | '-'): string[] {
  const sums = (balance: string) =>
    ['U256::from(1)', 'U256::ONE'].flatMap((one) => [`${balance} ${op} ${one}`, ...(op === '+' ? [`${one} + ${balance}`] : [])]);
  const fromLocal = sums('$x');
  const inline = sums(`self.balances.get(${account})`);
  const insert = (value: string) => `self.balances.insert(${account}, ${value})`;
  const set = (value: string) => `self.balances.setter(${account}).set(${value})`;
  return [
    ...fromLocal.flatMap((value) => [insert(value), set(value)]),
    ...inline.map(insert),
    ...[...fromLocal, ...inline].flatMap((value) => [`let $y = ${value}; ${insert('$y')}`, `let $y = ${value}; ${set('$y')}`]),
  ];
}

/**
 * Snippets for lesson 15's `supports_interface`: the answers of both components joined with `||`,
 * in either order, as method calls or with the trait syntax of the OpenZeppelin examples, inline or
 * read into locals first.
 */
function eitherSupports(): string[] {
  const token = ['self.erc20.supports_interface(interface_id)', 'Erc20::supports_interface(&self.erc20, interface_id)'];
  const metadata = ['self.metadata.supports_interface(interface_id)', 'Erc20Metadata::supports_interface(&self.metadata, interface_id)'];
  return token.flatMap((a) =>
    metadata.flatMap((b) => [
      `${a} || ${b}`,
      `${b} || ${a}`,
      ...[`let $a = ${a}; let $b = ${b};`, `let $b = ${b}; let $a = ${a};`].flatMap((locals) => [`${locals} $a || $b`, `${locals} $b || $a`]),
    ]),
  );
}

/**
 * Snippets for a static call of lesson 16 to `method` of the feed: on the feed kept in a local of
 * any name or built inline, with `Call::new()` or `Call::default()` written inline, or kept in a local
 * declared just before the statement of the call (with the feed's local in between, or not). The
 * statement returns the result, keeps it in a local or destructures the round. The result is passed
 * on with `?`. A configuration local is only accepted from `Call::new()` or `Call::default()`, so a
 * local holding `Call::new_mutating(self)` does not count.
 */
function feedCalls(method: string): string[] {
  const feeds = ['$f', 'IPriceFeed::new(self.feed.get())', 'IPriceFeed::from(self.feed.get())'];
  const configs = ['Call::new()', 'Call::default()'];
  const statements = ['', 'Ok(', 'let $d = ', 'let (_, $a, _, $u, _) = '];
  return [
    ...feeds.flatMap((feed) => configs.map((config) => `${feed}.${method}(self.vm(), ${config})?`)),
    ...configs.flatMap((config) =>
      statements.flatMap((statement) => [
        ...feeds.map((feed) => `let $c = ${config}; ${statement}${feed}.${method}(self.vm(), $c)?`),
        `let $c = ${config}; let $f = IPriceFeed::new(self.feed.get()); ${statement}$f.${method}(self.vm(), $c)?`,
      ]),
    ),
  ];
}

/**
 * Snippets for lesson 16's age check: the time since `updated_at` (kept in a local of any name)
 * greater than `max_age`, read inline or into a local, either way round; with `saturating_sub`; or as
 * `now` past `updated_at + max_age`.
 */
function staleConditions(): string[] {
  const ages = ['now - $u', 'now.saturating_sub($u)'];
  const limits = ['self.max_age.get()', '$m'];
  return [
    ...ages.flatMap((age) => limits.flatMap((limit) => [`if ${age} > ${limit} {`, `if ${limit} < ${age} {`])),
    ...limits.flatMap((limit) => [`if now > $u + ${limit} {`, `if $u + ${limit} < now {`]),
  ];
}

/**
 * Snippets for returning a custom error from a method that returns `Result<_, Vec<u8>>`: built in
 * place up to its fields, or kept in a local first (the error or the enum variant), then converted
 * with `.into()`. Each entry of `fieldLists` is one accepted way to write the fields.
 */
function intoErrorReturns(enumName: string, variant: string, fieldLists: string[]): string[] {
  return [
    `Err(${enumName}::${variant}(${variant} {`,
    ...fieldLists.flatMap((fields) =>
      [`${variant} { ${fields} }`, `${variant} { ${fields}, }`].flatMap((error) => [
        `let $x = ${error}; return Err(${enumName}::${variant}($x).into())`,
        `let $x = ${enumName}::${variant}(${error}); return Err($x.into())`,
      ]),
    ),
  ];
}

/**
 * Snippets for lesson 17's new round: the stored round plus one (`U80::from(1)` or `U80::ONE`, either
 * order), written with `set`, directly or from a local; or the stored round read into a local first.
 */
function nextRounds(): string[] {
  const values = ['U80::from(1)', 'U80::ONE'].flatMap((one) => [`self.round_id.get() + ${one}`, `${one} + self.round_id.get()`]);
  const fromRead = ['U80::from(1)', 'U80::ONE'].flatMap((one) => [
    `let $r = self.round_id.get(); self.round_id.set($r + ${one})`,
    `let $r = self.round_id.get(); self.round_id.set(${one} + $r)`,
  ]);
  return [...values.flatMap((value) => [`self.round_id.set(${value})`, `let $n = ${value}; self.round_id.set($n)`]), ...fromRead];
}

/** Receivers of lesson 5's token calls: the token kept in a local of any name, or built inline. */
const VAULT_TOKENS = ['$t', 'IERC20::new(self.token.get())', 'IERC20::from(self.token.get())'];

/**
 * Snippets for a writing call of lesson 5 to `method` of the token with one of `argLists`, the
 * configuration kept in a local (`Call::new_mutating(self)` written inline does not compile next to
 * `self.vm()`) and the result passed on with `?`. With `checked`, the call is followed by the test of
 * its `bool`: kept in a local of any name, or tested inline, with `!` or `== false`.
 */
function tokenCalls(method: string, argLists: string[], checked: boolean): string[] {
  return VAULT_TOKENS.flatMap((token) =>
    argLists.flatMap((args) => {
      const call = `${token}.${method}(self.vm(), $c, ${args})?`;
      return checked ? [`let $ok = ${call}; if !$ok {`, `let $ok = ${call}; if $ok == false {`, `if !${call} {`, `if ${call} == false {`] : [call];
    }),
  );
}

/** Snippets for lesson 5's credit: the deposit plus `amount` (either order), written with `insert` or `setter`, directly or from a local. */
function credits(): string[] {
  const sums = ['self.deposits.get(account) + amount', 'amount + self.deposits.get(account)'];
  return sums.flatMap((sum) => [
    `self.deposits.insert(account, ${sum})`,
    `let $x = ${sum}; self.deposits.insert(account, $x)`,
    `let $x = ${sum}; self.deposits.setter(account).set($x)`,
  ]);
}

/**
 * Snippets for lesson 5's withdrawal in checks-effects-interactions order: the deposit lowered, then
 * the token called. The token and the configuration may be kept in locals in between, in any order.
 */
function lowerThenSend(): string[] {
  const lowers = [
    'self.deposits.insert(account, available - amount);',
    'self.deposits.setter(account).set(available - amount);',
    'let $l = available - amount; self.deposits.insert(account, $l);',
    'let $l = available - amount; self.deposits.setter(account).set($l);',
  ];
  const setups = [
    '',
    'let $c = Call::new_mutating(self);',
    'let $t = IERC20::new(self.token.get()); let $c = Call::new_mutating(self);',
    'let $c = Call::new_mutating(self); let $t = IERC20::new(self.token.get());',
  ];
  const sends = tokenCalls('transfer', ['account, amount'], false).flatMap((call) => [`let $ok = ${call}`, `if !${call}`]);
  return lowers.flatMap((lower) => setups.flatMap((setup) => sends.map((send) => `${lower} ${setup} ${send}`)));
}

/**
 * Snippets for a method whose body computes one of `values`: returned as the tail expression, with
 * `return`, or from a local. Each snippet starts at the signature, so a value computed in another
 * method does not count.
 */
function methodBodies(signature: string, values: string[]): string[] {
  return values.flatMap((value) => {
    // A value that starts with locals (`let $p = ...; ink / $p`) keeps them before its result.
    const split = value.lastIndexOf(';');
    const [locals, result] = split === -1 ? ['', value] : [value.slice(0, split + 1) + ' ', value.slice(split + 1).trim()];
    return [`${signature} { ${locals}${result} }`, `${signature} { ${locals}return ${result}; }`, `${signature} { ${locals}let $r = ${result}; $r }`];
  });
}

/**
 * Snippets for lesson 18's overflow: the `None` of `checked_mul` turned into BudgetOverflow with
 * `ok_or` or `ok_or_else`, the fields in either order (rustfmt may add a trailing comma), or the
 * error built in a local right before the product.
 */
function budgetOverflows(): string[] {
  const errors = ['items, ink_per_item', 'ink_per_item, items'].flatMap((fields) =>
    [`BudgetOverflow { ${fields} }`, `BudgetOverflow { ${fields}, }`].map((error) => `BudgetError::BudgetOverflow(${error})`),
  );
  const products = ['items.checked_mul(ink_per_item)', 'ink_per_item.checked_mul(items)'];
  return [
    ...errors.flatMap((error) => [`.ok_or(${error})?`, `.ok_or_else(|| ${error})?`]),
    ...errors.flatMap((error) => products.map((product) => `let $x = ${error}; let ink = ${product}.ok_or($x)?`)),
  ];
}

